/** 取某音（音节+数字声调）的候选同音字；去掉「字本身」 */
export function homophoneCandidates(syllableTone: string, exclude?: string): string[] {
  const list = HOMOPHONES[syllableTone] || [];
  return exclude ? list.filter((c) => c !== exclude) : list.slice();
}
